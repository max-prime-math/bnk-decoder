function sourceRecord(path, number) {
  const bytes=inflateSync(readFileSync(path).subarray(16)), parsed=readQuestionRecords(bytes);
  const record=parsed.records.find(record=>record.number===number);
  const variables=new Map(readAlgorithmBlockAt(bytes,...record.prefix.algorithm).map(entry=>[entry.name,entry]));
  return {bytes,record,variables};
}
