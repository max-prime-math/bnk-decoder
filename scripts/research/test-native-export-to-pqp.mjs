import assert from 'node:assert/strict';
import fs from 'node:fs';
import { inflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { readQuestionRecords } from '../../packages/bnk-core/src/records.ts';
import { convertNativeExport } from '../native-export-to-pqp.mjs';
const bytes = fs.readFileSync('ignore/ExamView/Banks/Pre-Calculus 12/Chapter 01.bnk');
const bank = readQuestionRecords(inflateSync(bytes.subarray(16)));
const inventory = JSON.parse(fs.readFileSync('reports/rea-examview/runtime-oracle/chapter01-auto.inventory.json'));
const common = { sourceName: 'Chapter 01.bnk', sourceSha256: createHash('sha256').update(bytes).digest('hex'), bank, inventory };
const result = convertNativeExport(common);
assert.equal(result.counts.convertedRecords, 69);
assert.equal(result.counts.questions, 65);
assert.equal(result.pqp.extensions.nativeConversion.status, 'partial');
assert.deepEqual(result.pqp.extensions.nativeConversion.omittedQuestions.map(q => q.sourceId), ['question_34_1', 'question_35_1']);
assert.equal(result.pqp.questions[0].answer.value, 'c');
const matching = result.pqp.questions.find(q => q.kind === 'matching');
assert.equal(matching.extensions.examview.sourceRecords.length, 5);
assert.equal(matching.answer.value, '1. D\n2. F\n3. B\n4. C\n5. A');
assert.ok(result.diagnostics.some(d => d.code === 'NATIVE_MATCHING_KEY_CORRECTED'));
assert.ok(result.diagnostics.some(d => d.code === 'NATIVE_ORPHAN_MATCHING_CONDITION'));
assert.ok(result.pqp.questions.find(q => q.extensions.examview.nativeExportOrdinal === 37).extensions.examview.sourceRecords[0].number === 41);
const corrupted = structuredClone(inventory);
corrupted.assets[0].base64 = Buffer.from('invalid image').toString('base64');
const rejected = convertNativeExport({ ...common, inventory: corrupted });
assert.equal(rejected.counts.questions, 64);
assert.ok(rejected.diagnostics.some(d => d.message.includes('digest mismatch')));
assert.equal(bank.records[8].typeCode, 2, 'type 4 is bimodal; strict mismatch fixture must use actual type 2');
const wrongType = structuredClone(inventory);wrongType.items[8].type = 'Essay';
const mismatch = convertNativeExport({ ...common, inventory: wrongType });
assert.equal(mismatch.counts.questions, 8);
assert.ok(!mismatch.pqp.questions.some(q => q.extensions.examview.sourceRecords.some(r => r.number === 9)), 'type 2 Essay mismatch must remain omitted');
const firstEightAssets = new Set(result.pqp.questions.slice(0, 8).flatMap(q => q.assets ?? []));
assert.ok(mismatch.pqp.assets.every(a => firstEightAssets.has(a.id)), 'failed items must not leak staged image assets');
const mockRtf = { questions: [{ answerOrdinal: 34, hasAnswerMarker: true, answer: 'paired answer 34' }, { answerOrdinal: 35, hasAnswerMarker: true, answer: 'paired answer 35' }] };
const unverified = convertNativeExport({ ...common, rtf: mockRtf });
assert.equal(unverified.counts.convertedRecords, 69, 'unverified RTF cannot supply answers');
const paired = convertNativeExport({ ...common, rtf: mockRtf, pairedNativeEvidence: true });
assert.equal(paired.counts.convertedRecords, 71);
assert.equal(paired.pqp.extensions.nativeConversion.status, 'complete');
assert.equal(paired.pqp.questions.find(q => q.extensions.examview.nativeExportOrdinal === 34).answer.value, 'paired answer 34');
console.log('Native-export bridge regression passed: type/ordinal alignment, matching orphan/answers, paired-RTF gate, digest mismatch and staged-asset rollback.');
